import fs from "node:fs";
import path from "node:path";
import { renderStill, selectComposition } from "@remotion/renderer";
import { componentSpecs } from "@ai-history/schemas";
import { ROOT, type Episode } from "../context";
import { layoutCaption } from "../lib/linebreak";
import { readJson } from "../lib/util";
import { browserExecutable, getBundle } from "./render";

interface Fixture {
  component: string;
  name?: string;
  props: unknown;
  events?: Record<string, number>;
  texts?: Record<string, string>;
  captionCue?: string;
  frame: number;
  duration?: number;
}

// pnpm ep previews <ep>: one still per component (fixtures in packages/components/previews/fixtures.json).
// Words come from the episode's data, never from the fixtures or the components.
export async function previews(ep: Episode): Promise<void> {
  const dir = path.join(ROOT, "packages/components/previews");
  const fx = readJson<{ lang: string; items: Fixture[] }>(path.join(dir, "fixtures.json"));
  const lang = fx.lang;
  const resolve = (key: string) => (key.startsWith("doc:") ? ep.documents.documents[key.slice(4)].text : ep.strings[lang][key]);
  const serveUrl = await getBundle(ep);
  const browser = browserExecutable();
  for (const item of fx.items) {
    if (!componentSpecs[item.component as keyof typeof componentSpecs]) throw new Error(`fixture for unknown component ${item.component}`);
    let caption = null;
    if (item.captionCue) {
      const text = ep.scripts[lang].split("\n").find((l) => l.startsWith(`{#${item.captionCue}}`))!.replace(/^\{#\w+\}\s*/, "").replace(/\s*\[\[.*\]\]\s*$/, "");
      const style = ep.bible.languages[lang];
      const lines = layoutCaption(text, { maxLineChars: style.caption.maxLineChars, unit: style.unit, dropLineEndPunct: style.caption.dropLineEndPunct }, style.caption.maxLines)[0];
      caption = { index: 1, cue: item.captionCue, shot: "S01", startFrame: 0, endFrame: 10, lines };
    }
    const preview = {
      bible: ep.bible,
      lang,
      component: item.component,
      props: item.props,
      events: item.events ?? {},
      texts: Object.fromEntries(Object.entries(item.texts ?? {}).map(([k, v]) => [k, resolve(v)])),
      caption,
      label: ep.strings[lang].ai_label,
      duration: item.duration ?? item.frame + 1,
    };
    const inputProps = { preview };
    const composition = await selectComposition({ serveUrl, id: "Preview", inputProps, browserExecutable: browser, logLevel: "error" });
    const name = item.name ?? item.component.split("/")[1];
    const out = path.join(dir, `${name}.png`);
    await renderStill({ composition, serveUrl, inputProps, output: out, frame: item.frame, scale: 0.5, browserExecutable: browser, logLevel: "error" });
    ep.log.info(`[previews] ${item.component} → ${path.relative(ROOT, out)}`);
  }
  const listed = new Set(fx.items.map((i) => i.component));
  const missing = Object.keys(componentSpecs).filter((c) => !listed.has(c));
  if (missing.length) ep.log.warn(`[previews] no preview yet (component not built): ${missing.join(", ")}`);
  fs.writeFileSync(path.join(dir, "README.md"), `# Component previews\n\nGenerated by \`pnpm ep previews ${ep.id}\` from \`fixtures.json\`. Do not edit the PNGs by hand.\n`);
}
